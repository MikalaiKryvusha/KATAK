const pathOf = (pts, close = false) => 'M' + pts.map(([x, y]) => `${f(x)} ${f(y)}`).join(' L') + (close ? ' Z' : '');
// Archimedean spiral arm seen from the front: radius grows linearly with the swept angle (the turbine's blade edge).
function spiralArm(k, n, rHub, rOut, sweep, steps = 60, spin = -1) {
  const pts = [];
  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    const a = TAU * k / n + spin * sweep * t - Math.PI / 2;
    const r = rHub + (rOut - rHub) * t;
    pts.push([C + r * Math.cos(a), C + r * Math.sin(a)]);
  }
  return pts;
}
// A crescent blade: the outer edge is the spiral arm, the inner edge lags behind it and thickens toward the tip.
function crescent(k, n, rHub, rOut, sweep, thick = 0.42, steps = 60) {
  const outer = spiralArm(k, n, rHub, rOut, sweep, steps);
  const inner = [];
  for (let i = steps; i >= 0; i--) {
    const t = i / steps;
    const a = TAU * k / n - sweep * t - Math.PI / 2;
    const r = rHub + (rOut - rHub) * t * (1 - thick * t);
    inner.push([C + r * Math.cos(a), C + r * Math.sin(a)]);
  }
  return [...outer, ...inner];
}

