// A blade born from the rim: its outer edge reaches the rim TANGENTIALLY (r = rh + (R − rh)·(1 − (1 − t)²), dr/dt = 0 at t = 1),
// the blade is thickest in the middle; `tipW` is its width where it enters the rim (0 — it thins to a point and merges).
function rimBlade(k, rh, R, sweep, thick, tipW, steps = 80) {
  const ease = (t) => 1 - (1 - t) * (1 - t);
  const outer = [], inner = [];
  for (let i = 0; i <= steps; i++) {
    const t = i / steps, a = TAU * k / 3 - sweep * t - Math.PI / 2, ro = rh + (R - rh) * ease(t);
    outer.push([C + ro * Math.cos(a), C + ro * Math.sin(a)]);
    const w = thick * (R - rh) * Math.sin(Math.PI * Math.min(1, t * 1.15)) * (1 - t) + tipW * t * t;
    const ri = Math.max(rh, ro - w);
    inner.push([C + ri * Math.cos(a - 0.08 * (1 - t)), C + ri * Math.sin(a - 0.08 * (1 - t))]);
  }
  return [...outer, ...inner.reverse()];
}
