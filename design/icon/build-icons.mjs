// Logarithmic (nautilus) spiral: r = a·e^(bθ); b = ln(3)/2π — the shell triples its radius per turn.
const LOG_B = Math.log(3) / TAU;
function nautilusShell(R, turns = 2.2, steps = 220) {
  const thEnd = TAU * turns, a = R / Math.exp(LOG_B * thEnd);
  const at = (th, rot = 0.6) => { const r = a * Math.exp(LOG_B * th); return [C + 6 + r * Math.cos(th + rot), C + 4 + r * Math.sin(th + rot)]; };
  const outer = [], inner = [];
  for (let i = 0; i <= steps; i++) outer.push(at(thEnd * i / steps));
  for (let i = steps; i >= 0; i--) { const th = thEnd * i / steps; inner.push(at(Math.max(0, th - TAU))); }
  const septa = [];
  for (let th = thEnd - 0.35; th > TAU * 0.55; th -= 0.62) septa.push([at(th), at(th - TAU)]);
  return { shell: [...outer, ...inner], septa, spiral: outer };
}

